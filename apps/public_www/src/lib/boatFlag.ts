export type BoatFlagBox = {
  x: number
  y: number
  width: number
  height: number
}

/** Flag rectangle for a playback time, or null when the junk's flag is off-screen. */
export function boatFlagAtTime(seconds: number): BoatFlagBox | null {
  if (!Number.isFinite(seconds)) return null
  const frame = Math.round(seconds * BOAT_FLAG.fps)
  if (frame < 0 || frame >= BOAT_FLAG_X.length) return null
  const x = BOAT_FLAG_X[frame]
  const { y, width, height, videoWidth } = BOAT_FLAG
  if (x + width <= 0 || x >= videoWidth) return null
  return { x, y, width, height }
}
